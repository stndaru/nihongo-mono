/**
 * Prepare the pinned PaddleOCR.js worker/runtime and verify the committed
 * PP-OCRv5 model archives. All downloadable files are gzip containers;
 * the browser verifies them, inflates them into Cache Storage, then the
 * service worker exposes their ordinary target URLs to the OCR worker.
 */
import { createHash } from 'node:crypto'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { basename, join } from 'node:path'
import { gunzipSync, gzipSync } from 'node:zlib'

const VERSION = 'v0.4.2' // sync: src/lib/ocr/assets.ts
const ROOT = join(import.meta.dirname, '..')
const OUT = join(ROOT, 'public', 'ocr', 'paddle', VERSION)
const DOWNLOAD = join(OUT, 'download')
const PACKAGE_ROOT = join(ROOT, 'node_modules', '@paddleocr', 'paddleocr-js')
const ORT_ROOT = join(ROOT, 'node_modules', 'onnxruntime-web')
const OCR_ROOT = join(ROOT, 'public', 'ocr')
const LICENSE_ROOT = join(OCR_ROOT, 'paddle', 'licenses')
const MODEL_SHA256: Record<string, string> = {
  'ppocrv5-mobile-det.tar.gz': '635dcb3ad4ee25aa77fbc9d58eb3b0269327c64b0db7ab6b600755d08e6276b0',
  'ppocrv5-mobile-rec.tar.gz': '92b138ed6adfb65f6eefa80d176ebd7802ae3f0783fce2af7225ad939b82405d',
}

interface AssetSpec {
  sourceName: string
  target: string
  contentType: string
  raw: Uint8Array
  committed?: boolean
}

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex')
}

function requirePackageVersion(): void {
  const pkg = JSON.parse(readFileSync(join(PACKAGE_ROOT, 'package.json'), 'utf8')) as {
    version?: string
  }
  if (`v${pkg.version}` !== VERSION) {
    throw new Error(`PaddleOCR.js ${pkg.version ?? 'unknown'} does not match ${VERSION}`)
  }
}

function findWorker(): string {
  const dir = join(PACKAGE_ROOT, 'dist', 'assets')
  const matches = readdirSync(dir).filter(
    (name) => name.startsWith('worker-entry-') && name.endsWith('.js'),
  )
  if (matches.length !== 1) {
    throw new Error(`expected one Paddle worker in ${dir}, found ${matches.length}`)
  }
  return join(dir, matches[0])
}

function committedModel(name: string): Uint8Array {
  const file = join(DOWNLOAD, name)
  if (!existsSync(file)) {
    throw new Error(`${file} is missing — see docs/development.md for the pinned model source`)
  }
  const compressed = readFileSync(file)
  if (sha256(compressed) !== MODEL_SHA256[name]) {
    throw new Error(`${file} does not match the pinned official model checksum`)
  }
  return gunzipSync(compressed)
}

