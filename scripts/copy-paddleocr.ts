requirePackageVersion()
mkdirSync(DOWNLOAD, { recursive: true })
writeThirdPartyLicenses()

const specs: AssetSpec[] = [
  {
    sourceName: 'worker.js.gz',
    target: `/ocr/paddle/${VERSION}/worker.js`,
    contentType: 'text/javascript; charset=utf-8',
    raw: readFileSync(findWorker()),
  },
  {
    sourceName: 'ort-wasm-simd-threaded.jsep.wasm.gz',
    target: `/ocr/paddle/${VERSION}/runtime/ort-wasm-simd-threaded.jsep.wasm`,
    contentType: 'application/wasm',
    raw: readFileSync(join(ORT_ROOT, 'dist', 'ort-wasm-simd-threaded.jsep.wasm')),
  },
  {
    sourceName: 'ort-wasm-simd-threaded.jsep.mjs.gz',
    target: `/ocr/paddle/${VERSION}/runtime/ort-wasm-simd-threaded.jsep.mjs`,
    contentType: 'text/javascript; charset=utf-8',
    raw: readFileSync(join(ORT_ROOT, 'dist', 'ort-wasm-simd-threaded.jsep.mjs')),
  },
  {
    sourceName: 'ppocrv5-mobile-det.tar.gz',
    target: `/ocr/paddle/${VERSION}/models/PP-OCRv5_mobile_det.tar`,
    contentType: 'application/octet-stream',
    raw: committedModel('ppocrv5-mobile-det.tar.gz'),
    committed: true,
  },
  {
    sourceName: 'ppocrv5-mobile-rec.tar.gz',
    target: `/ocr/paddle/${VERSION}/models/PP-OCRv5_mobile_rec.tar`,
    contentType: 'application/octet-stream',
    raw: committedModel('ppocrv5-mobile-rec.tar.gz'),
    committed: true,
  },
]

const files = specs.map((spec) => {
  const output = join(DOWNLOAD, spec.sourceName.replace(/\.gz$/u, '.pack'))
  const compressed = spec.committed
    ? readFileSync(join(DOWNLOAD, spec.sourceName))
    : gzipSync(spec.raw, { level: 9 })
  if (!existsSync(output) || !readFileSync(output).equals(compressed)) {
    writeFileSync(output, compressed)
  }
  return {
    source: `/ocr/paddle/${VERSION}/download/${basename(output)}`,
    target: spec.target,
    bytes: statSync(output).size,
    inflatedBytes: spec.raw.byteLength,
    sha256: sha256(compressed),
    contentType: spec.contentType,
  }
})

const manifest = {
  version: VERSION,
  totalBytes: files.reduce((sum, file) => sum + file.bytes, 0),
  files,
}
writeFileSync(join(OUT, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
const fallbackFiles = [
  '/ocr/engine/tesseract-client.js',
  '/ocr/engine/tesseract-worker.js',
  '/ocr/engine/tesseract-core.wasm',
  '/ocr/engine/tesseract-core-fallback.wasm',
  '/ocr/models/jpn.traineddata.gz',
  '/ocr/models/eng.traineddata.gz',
].map((path) => [path, statSync(join(ROOT, 'public', path)).size] as const)
const offlineManifest = {
  version: VERSION,
  paddleBytes: manifest.totalBytes,
  totalBytes: manifest.totalBytes + fallbackFiles.reduce((sum, [, bytes]) => sum + bytes, 0),
  files: fallbackFiles,
}
writeFileSync(
  join(OCR_ROOT, 'offline-manifest.json'),
  `${JSON.stringify(offlineManifest, null, 2)}\n`,
)
console.log(
  `copy-paddleocr: ${files.length} Paddle files, ${(manifest.totalBytes / 1048576).toFixed(1)} MB compressed; ${(offlineManifest.totalBytes / 1048576).toFixed(1)} MB full offline OCR pack`,
)
